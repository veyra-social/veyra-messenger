//! Update checker client (plan ратифицирован 2026-07-21, сайт-endpoint живой
//! с 2026-07-22; план из next-steps убран, когда сайтовая часть была сделана).
//!
//! Principles (ratified): the client only LEARNS that a newer version exists
//! — no auto-download, no auto-install, no telemetry. The request is one bare
//! GET without identifiers; the only client data on the wire is the
//! version-bearing `User-Agent` / `X-Veyra-Client` header pair the site uses
//! as its bot barrier (no header → 404). Results are cached in per-profile
//! app_meta so the About dialog renders instantly without touching the
//! network.
//!
//! Cadence: the quiet auto-check runs at most once per ~72 h (±6 h jitter),
//! is checkbox-controlled (on by default) and is triggered a few minutes
//! after unlock — never at startup. The About button does an immediate
//! manual check.
//!
//! Trust: the manifest is signed with an offline release key and verified
//! against `RELEASE_PUBLIC_KEY_B64` before anything in it is stored or shown.
//! HTTPS says the bytes came from the site; the signature says they came from
//! us. What the signature covers is defined once in `update_manifest.rs` and
//! shared with `tools/release-signer`, which the release flow runs — an
//! unsigned `latest.json` never reaches the site, and if one did, the client
//! would refuse it.

use std::collections::HashMap;
use std::io::Read;
use std::time::Duration;

use serde::{Deserialize, Serialize};

use crate::errors::{AppError, AppResult};
use crate::storage::db;
use crate::update_manifest::{SignedManifest, SignedPlatform};
use crate::version::APP_VERSION;

const LATEST_JSON_URL: &str = "https://veyra.social/releases/latest.json";
/// Where the About dialog sends the user when the manifest offers no URL, or
/// offers one we will not open.
const DEFAULT_UPDATE_URL: &str = "https://veyra.social";
/// Public half of the offline release key (`release-signing/update-manifest.key`,
/// generated 2026-07-28). A manifest that does not verify against it is not a
/// release announcement from us, whatever served it. Changing this constant
/// invalidates every manifest signed with the old key, so it moves only with a
/// deliberate key rotation.
const RELEASE_PUBLIC_KEY_B64: &str = "xH35N5QbsoU4CcHy4y30iRjm9ubj1E6DYvUVJa0ocpc=";
/// Hosts an update URL may point at: our own site (including subdomains such
/// as `release.veyra.social`) and the official stores we publish through.
const UPDATE_URL_HOSTS: [&str; 4] = [
    "veyra.social",
    "play.google.com",
    "apps.apple.com",
    "apps.microsoft.com",
];
const MANIFEST_SCHEMA: u64 = 1;
const MAX_MANIFEST_BYTES: usize = 16 * 1024;
const FETCH_TIMEOUT: Duration = Duration::from_secs(10);
const CONNECT_TIMEOUT: Duration = Duration::from_secs(5);
/// Quiet auto-check cadence: at most once per 72 h, jittered ±6 h so a fleet
/// of clients never synchronizes on the site.
const AUTO_CHECK_INTERVAL_SECONDS: i64 = 72 * 60 * 60;
const AUTO_CHECK_JITTER_SECONDS: i64 = 6 * 60 * 60;

// app_meta keys (plaintext meta, readable without unlock — same class as
// `background_restricted`).
const META_AUTO_CHECK: &str = "update_auto_check";
const META_LAST_CHECK_AT: &str = "update_last_check_at";
const META_LATEST_VERSION: &str = "update_latest_version";
const META_LATEST_URL: &str = "update_latest_url";
const META_ETAG: &str = "update_manifest_etag";

/// `latest.json` schema 1 (generated by releasepack). Unknown fields are
/// ignored so the schema can grow without breaking older clients — but a
/// field the signature does not cover must never change what this client
/// does, so anything acted upon here is also in `SignedManifest`.
#[derive(Deserialize)]
struct Manifest {
    schema: u64,
    version: String,
    #[serde(default)]
    published_at: Option<String>,
    #[serde(default)]
    download_url: Option<String>,
    #[serde(default)]
    platforms: HashMap<String, ManifestPlatform>,
    /// Base64 Ed25519 signature over `update_manifest::signing_bytes`.
    #[serde(default)]
    sig: Option<String>,
}

#[derive(Deserialize, Default)]
struct ManifestPlatform {
    #[serde(default)]
    file: Option<String>,
    #[serde(default)]
    size: Option<u64>,
    #[serde(default)]
    sha256: Option<String>,
    #[serde(default)]
    store_url: Option<String>,
}

impl Manifest {
    /// Re-renders the manifest in the form the release key signed.
    fn signed_view(&self) -> SignedManifest {
        SignedManifest {
            schema: self.schema,
            version: self.version.clone(),
            published_at: self.published_at.clone().unwrap_or_default(),
            download_url: self.download_url.clone().unwrap_or_default(),
            platforms: self
                .platforms
                .iter()
                .map(|(key, platform)| SignedPlatform {
                    key: key.clone(),
                    file: platform.file.clone().unwrap_or_default(),
                    size: platform
                        .size
                        .map(|size| size.to_string())
                        .unwrap_or_default(),
                    sha256: platform.sha256.clone().unwrap_or_default(),
                    store_url: platform.store_url.clone().unwrap_or_default(),
                })
                .collect(),
        }
    }
}

/// What the About dialog renders. `update_url` is the store page when the
/// manifest carries one for this platform, the site download page otherwise.
#[derive(Debug, Clone, Serialize)]
pub struct UpdateCheckStatus {
    pub current_version: &'static str,
    pub latest_version: Option<String>,
    pub update_available: bool,
    pub update_url: Option<String>,
    pub last_checked_at: Option<i64>,
    pub auto_check_enabled: bool,
}

fn check_failed(reason: String) -> AppError {
    AppError::UpdateCheckFailed(reason)
}

/// Cached view — no network.
pub fn status(conn: &rusqlite::Connection) -> AppResult<UpdateCheckStatus> {
    let latest_version = db::get_meta(conn, META_LATEST_VERSION)?;
    let update_available = latest_version
        .as_deref()
        .is_some_and(|latest| version_is_newer(latest, APP_VERSION));
    Ok(UpdateCheckStatus {
        current_version: APP_VERSION,
        latest_version,
        update_available,
        update_url: db::get_meta(conn, META_LATEST_URL)?,
        last_checked_at: db::get_meta(conn, META_LAST_CHECK_AT)?.and_then(|s| s.parse().ok()),
        auto_check_enabled: auto_check_enabled(conn)?,
    })
}

/// The About checkbox. Default is enabled (the plan's quiet 72 h check).
pub fn auto_check_enabled(conn: &rusqlite::Connection) -> AppResult<bool> {
    Ok(!matches!(
        db::get_meta(conn, META_AUTO_CHECK)?.as_deref(),
        Some("0")
    ))
}

pub fn set_auto_check(conn: &rusqlite::Connection, enabled: bool) -> AppResult<()> {
    db::set_meta(conn, META_AUTO_CHECK, if enabled { "1" } else { "0" })
}

fn now_unix() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

/// Manual check (About button): one bounded HTTPS GET, result persisted.
pub fn check_now(data_dir: &std::path::Path) -> AppResult<UpdateCheckStatus> {
    let conn = db::open_db(data_dir)?;
    fetch_and_store(&conn)?;
    status(&conn)
}

/// Quiet post-unlock path: no-op unless the checkbox is on and the 72 h
/// (jittered) cadence says a check is due. Fetch errors are swallowed — the
/// next unlock retries; nothing is surfaced to the user.
pub fn auto_check_if_due(data_dir: &std::path::Path) -> AppResult<UpdateCheckStatus> {
    let conn = db::open_db(data_dir)?;
    if auto_check_enabled(&conn)? {
        let last: i64 = db::get_meta(&conn, META_LAST_CHECK_AT)?
            .and_then(|s| s.parse().ok())
            .unwrap_or(0);
        let jitter = rand::Rng::gen_range(
            &mut rand::thread_rng(),
            -AUTO_CHECK_JITTER_SECONDS..=AUTO_CHECK_JITTER_SECONDS,
        );
        if now_unix() >= last + AUTO_CHECK_INTERVAL_SECONDS + jitter {
            if let Err(error) = fetch_and_store(&conn) {
                tracing::info!(%error, "quiet update check failed; will retry next unlock");
            }
        }
    }
    status(&conn)
}

/// GET latest.json (with `If-None-Match` when we hold an ETag), validate,
/// persist. 304 only refreshes the check timestamp.
fn fetch_and_store(conn: &rusqlite::Connection) -> AppResult<()> {
    // `apply` pins the direct path with an explicit `no_proxy()` when proxy
    // mode is off, and routes the check through the proxy when it is on —
    // an update check must not be the one request that ignores the setting.
    let client = crate::p2p::proxy::apply(
        reqwest::blocking::Client::builder()
            .https_only(true)
            .redirect(reqwest::redirect::Policy::none())
            .referer(false)
            .connect_timeout(CONNECT_TIMEOUT)
            .timeout(FETCH_TIMEOUT)
            .user_agent(format!("Veyra/{APP_VERSION} ({})", std::env::consts::OS)),
    )
    .map_err(|err| check_failed(format!("http client: {err}")))?
    .build()
    .map_err(|err| check_failed(format!("http client: {err}")))?;
    let mut request = client
        .get(LATEST_JSON_URL)
        .header(reqwest::header::ACCEPT, "application/json")
        .header("X-Veyra-Client", APP_VERSION);
    if let Some(etag) = db::get_meta(conn, META_ETAG)? {
        request = request.header(reqwest::header::IF_NONE_MATCH, etag);
    }
    let response = request
        .send()
        .map_err(|err| check_failed(format!("request failed: {err}")))?;
    if response.status() == reqwest::StatusCode::NOT_MODIFIED {
        db::set_meta(conn, META_LAST_CHECK_AT, &now_unix().to_string())?;
        return Ok(());
    }
    if response.status() != reqwest::StatusCode::OK {
        return Err(check_failed(format!("http status {}", response.status())));
    }
    let etag = response
        .headers()
        .get(reqwest::header::ETAG)
        .and_then(|value| value.to_str().ok())
        .map(str::to_string);
    let mut body = Vec::new();
    response
        .take((MAX_MANIFEST_BYTES + 1) as u64)
        .read_to_end(&mut body)
        .map_err(|err| check_failed(format!("read failed: {err}")))?;
    if body.len() > MAX_MANIFEST_BYTES {
        return Err(check_failed("response too large".to_string()));
    }
    let manifest: Manifest = serde_json::from_slice(&body)
        .map_err(|_| check_failed("manifest is not valid json".to_string()))?;
    if manifest.schema != MANIFEST_SCHEMA {
        return Err(check_failed(format!(
            "unsupported manifest schema {}",
            manifest.schema
        )));
    }
    if parse_version(&manifest.version).is_none() {
        return Err(check_failed("manifest version unparseable".to_string()));
    }
    // The signature, not the transport, is what makes this a release
    // announcement from us. An unsigned or badly signed manifest is dropped
    // whole — nothing from it is stored or shown.
    let signature = manifest
        .sig
        .clone()
        .ok_or_else(|| check_failed("manifest is not signed".to_string()))?;
    if !crate::update_manifest::verify_manifest_signature(
        RELEASE_PUBLIC_KEY_B64,
        &signature,
        &manifest.signed_view(),
    ) {
        return Err(check_failed(
            "manifest signature does not verify".to_string(),
        ));
    }
    // Mobile builds open the store page once the manifest carries one; every
    // other platform (and mobile until then) goes to the site download page.
    let store_url = manifest
        .platforms
        .get(std::env::consts::OS)
        .and_then(|platform| platform.store_url.clone());
    // The manifest says where to send the user, and the About dialog opens
    // that URL in the system browser. A compromised site, CDN or TLS
    // terminator would otherwise choose the destination (code review
    // 2026-07-27, P2), so an URL that is not ours or an official store is
    // dropped rather than stored.
    let update_url = store_url
        .or(manifest.download_url)
        .and_then(|candidate| match allowed_update_url(&candidate) {
            true => Some(candidate),
            false => {
                tracing::warn!(url = %candidate, "update manifest url rejected");
                None
            }
        })
        .unwrap_or_else(|| DEFAULT_UPDATE_URL.to_string());
    db::set_meta(conn, META_LATEST_VERSION, &manifest.version)?;
    db::set_meta(conn, META_LATEST_URL, &update_url)?;
    db::set_meta(conn, META_LAST_CHECK_AT, &now_unix().to_string())?;
    if let Some(etag) = etag {
        db::set_meta(conn, META_ETAG, &etag)?;
    }
    tracing::info!(latest = %manifest.version, "update check completed");
    Ok(())
}

/// True when a manifest-supplied URL is one we are willing to open in the
/// user's browser: HTTPS, no embedded credentials, and a host that is ours or
/// an official store.
fn allowed_update_url(candidate: &str) -> bool {
    let Ok(url) = reqwest::Url::parse(candidate) else {
        return false;
    };
    if url.scheme() != "https" || !url.username().is_empty() || url.password().is_some() {
        return false;
    }
    let Some(host) = url.host_str() else {
        return false;
    };
    let host = host.trim_end_matches('.').to_ascii_lowercase();
    UPDATE_URL_HOSTS
        .iter()
        .any(|allowed| host == *allowed || host.ends_with(&format!(".{allowed}")))
}

/// Semver-precedence identifier: numeric identifiers compare numerically and
/// rank below alphanumeric ones.
#[derive(PartialEq, Eq, PartialOrd, Ord)]
enum Ident {
    Num(u64),
    Alpha(String),
}

/// Parses `X.Y.Z[-prerelease][+build]`; build metadata is ignored.
fn parse_version(raw: &str) -> Option<((u64, u64, u64), Option<Vec<Ident>>)> {
    let raw = raw.trim();
    let raw = raw.split('+').next()?;
    let (base, prerelease) = match raw.split_once('-') {
        Some((base, pre)) => (base, Some(pre)),
        None => (raw, None),
    };
    let mut parts = base.split('.');
    let major = parts.next()?.parse().ok()?;
    let minor = parts.next()?.parse().ok()?;
    let patch = parts.next()?.parse().ok()?;
    if parts.next().is_some() {
        return None;
    }
    let prerelease = match prerelease {
        None => None,
        Some(pre) if pre.is_empty() => return None,
        Some(pre) => Some(
            pre.split('.')
                .map(|ident| match ident.parse::<u64>() {
                    Ok(num) => Ident::Num(num),
                    Err(_) => Ident::Alpha(ident.to_string()),
                })
                .collect(),
        ),
    };
    Some(((major, minor, patch), prerelease))
}

/// Semver precedence: is `candidate` strictly newer than `current`?
/// A release outranks its own pre-releases (`1.0.0` > `1.0.0-rc.1`);
/// unparseable input is never "newer".
pub fn version_is_newer(candidate: &str, current: &str) -> bool {
    let (Some((cand_base, cand_pre)), Some((cur_base, cur_pre))) =
        (parse_version(candidate), parse_version(current))
    else {
        return false;
    };
    if cand_base != cur_base {
        return cand_base > cur_base;
    }
    match (cand_pre, cur_pre) {
        (None, Some(_)) => true,
        (None, None) | (Some(_), None) => false,
        (Some(cand), Some(cur)) => cand > cur,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The pinned key and the signed view must line up with what the signer
    /// produces: a manifest signed the way `release-signer` signs one has to
    /// verify here, and any edit to it must not.
    #[test]
    fn a_manifest_signed_by_the_release_key_verifies_through_the_client_view() {
        use base64::{engine::general_purpose::STANDARD, Engine as _};
        use ed25519_dalek::{Signer, SigningKey};

        let key = SigningKey::from_bytes(&[13_u8; 32]);
        let public_b64 = STANDARD.encode(key.verifying_key().to_bytes());
        let json = r#"{
            "schema": 1,
            "version": "1.26.36",
            "published_at": "2026-07-28T09:00:00Z",
            "download_url": "https://veyra.social/download",
            "platforms": {
                "windows-x64": {"file": "Veyra-setup.exe", "size": 51200000, "sha256": "abc"},
                "android": {"file": "Veyra.apk", "size": 72000000, "sha256": "def", "store_url": null}
            },
            "sig": null
        }"#;
        let manifest: Manifest = serde_json::from_str(json).unwrap();
        let signature = STANDARD.encode(
            key.sign(&crate::update_manifest::signing_bytes(&manifest.signed_view()).unwrap())
                .to_bytes(),
        );
        assert!(crate::update_manifest::verify_manifest_signature(
            &public_b64,
            &signature,
            &manifest.signed_view()
        ));

        // The same manifest with the download URL swapped — the case the
        // signature exists for.
        let tampered: Manifest = serde_json::from_str(
            &json.replace("https://veyra.social/download", "https://evil.com"),
        )
        .unwrap();
        assert!(!crate::update_manifest::verify_manifest_signature(
            &public_b64,
            &signature,
            &tampered.signed_view()
        ));

        // And it does not verify against the key we actually ship.
        assert!(!crate::update_manifest::verify_manifest_signature(
            RELEASE_PUBLIC_KEY_B64,
            &signature,
            &manifest.signed_view()
        ));
    }

    /// A fixture produced by the real `tools/release-signer` with the real
    /// release key, verified here against the real pinned public key. This is
    /// the only test that proves signer and client agree on the signed bytes
    /// for actual JSON — a change to `signing_bytes` that looks harmless in
    /// both places fails here.
    #[test]
    fn the_signer_and_this_client_agree_on_a_real_signed_manifest() {
        let signed = r#"{
  "download_url": "https://veyra.social/download",
  "platforms": {
    "android": {
      "file": "Veyra_1.26.36_arm64-v8a-release.apk",
      "sha256": "bbb",
      "size": 72000000,
      "store_url": null
    },
    "windows-x64": {
      "file": "Veyra_1.26.36_x64-setup.exe",
      "sha256": "aaa",
      "size": 51200000
    }
  },
  "published_at": "2026-07-28T09:30:00Z",
  "schema": 1,
  "sig": "Fs5fRaoEyozvNaM/h16xJsoZY6uO8Oy4BdIUW2mYN5bZvo3oAm7oVRof1zqgp92PzrEwlo2t0HejZrRlL+BrCg==",
  "version": "1.26.36"
}"#;
        let manifest: Manifest = serde_json::from_str(signed).unwrap();
        assert!(crate::update_manifest::verify_manifest_signature(
            RELEASE_PUBLIC_KEY_B64,
            manifest.sig.as_deref().unwrap(),
            &manifest.signed_view()
        ));

        // Same signature, one field moved: the version the user is told about.
        let tampered: Manifest =
            serde_json::from_str(&signed.replace("1.26.36", "9.99.9")).unwrap();
        assert!(!crate::update_manifest::verify_manifest_signature(
            RELEASE_PUBLIC_KEY_B64,
            tampered.sig.as_deref().unwrap(),
            &tampered.signed_view()
        ));
    }

    /// The pinned key must stay a well-formed Ed25519 public key: a typo here
    /// would reject every release announcement, silently.
    #[test]
    fn the_pinned_release_key_is_a_valid_ed25519_key() {
        use base64::{engine::general_purpose::STANDARD, Engine as _};
        let bytes = STANDARD
            .decode(RELEASE_PUBLIC_KEY_B64)
            .expect("pinned release key is not base64");
        let bytes: [u8; 32] = bytes
            .as_slice()
            .try_into()
            .expect("pinned release key is not 32 bytes");
        ed25519_dalek::VerifyingKey::from_bytes(&bytes).expect("pinned release key is not a point");
    }

    /// The URL in the manifest is signed now, but the allowlist stays: it is
    /// what limits the damage if the release key itself is ever misused, and
    /// it is the check that does not depend on key hygiene.
    #[test]
    fn only_our_own_and_store_https_urls_are_opened() {
        for allowed in [
            "https://veyra.social",
            "https://veyra.social/download",
            "https://release.veyra.social/1.26.35/Veyra.exe",
            "https://play.google.com/store/apps/details?id=app.veyra.messenger",
            "https://apps.apple.com/app/veyra/id123456789",
            "https://apps.microsoft.com/detail/veyra",
        ] {
            assert!(allowed_update_url(allowed), "rejected {allowed}");
        }
        for rejected in [
            // Not HTTPS.
            "http://veyra.social/download",
            "file:///C:/Windows/System32/evil.exe",
            "javascript:alert(1)",
            // Not our host — including the lookalikes.
            "https://evil.com/veyra.exe",
            "https://veyra.social.evil.com/download",
            "https://notveyra.social/download",
            // Credentials in the authority, which is how a URL is made to
            // read as ours at a glance.
            "https://veyra.social@evil.com/download",
            "https://user:pass@evil.com/veyra.social",
            "not a url at all",
            "",
        ] {
            assert!(!allowed_update_url(rejected), "accepted {rejected}");
        }
    }

    #[test]
    fn release_outranks_its_prereleases_and_older_versions() {
        assert!(version_is_newer("1.0.0", "1.0.0-rc.1"));
        assert!(version_is_newer("1.0.0-rc.2", "1.0.0-rc.1"));
        assert!(version_is_newer("1.0.0-rc.1", "0.9.688"));
        assert!(version_is_newer("1.0.1", "1.0.0"));
        assert!(version_is_newer("1.1.0-rc.1", "1.0.0"));
    }

    #[test]
    fn equal_or_older_is_not_newer() {
        assert!(!version_is_newer("1.0.0", "1.0.0"));
        assert!(!version_is_newer("1.0.0-rc.1", "1.0.0-rc.1"));
        assert!(!version_is_newer("1.0.0-rc.1", "1.0.0"));
        assert!(!version_is_newer("0.9.688", "1.0.0-rc.1"));
        assert!(!version_is_newer("1.0.0-rc.9", "1.0.0-rc.10"));
    }

    #[test]
    fn garbage_is_never_newer() {
        assert!(!version_is_newer("", "1.0.0"));
        assert!(!version_is_newer("newest", "1.0.0"));
        assert!(!version_is_newer("2.0", "1.0.0"));
        assert!(!version_is_newer("1.0.0-", "1.0.0-rc.1"));
        assert!(!version_is_newer("1.0.0.0", "1.0.0"));
    }

    #[test]
    fn numeric_prerelease_idents_rank_below_alpha() {
        // semver: 1.0.0-rc.1 < 1.0.0-rc.a (numeric < alphanumeric)
        assert!(version_is_newer("1.0.0-rc.a", "1.0.0-rc.1"));
        // build metadata is ignored
        assert!(!version_is_newer("1.0.0+build5", "1.0.0"));
    }
}
